def _risk_band(score: int) -> str:
    if score <= 3:
        return "Low"
    if score <= 6:
        return "Moderate"
    return "High"


def _format_risk_assessment(risk_scores: dict) -> str:
    if not risk_scores:
        return "## Risk Assessment\nRisk scoring has not completed yet."

    risk_fields = [
        ("Overall Risk", "overall_risk"),
        ("Financial Risk", "financial_risk"),
        ("Reputational Risk", "reputational_risk"),
        ("Market Risk", "market_risk"),
    ]
    lines = ["## Risk Assessment"]
    for label, key in risk_fields:
        value = risk_scores.get(key)
        if value is None:
            continue
        lines.append(f"- **{label}:** {value}/10 ({_risk_band(int(value))})")

    rationale = risk_scores.get("rationale")
    if rationale:
        lines.append(f"\n**Rationale:** {rationale}")
    return "\n".join(lines)


def _format_competitive_landscape(competitors: list) -> str:
    if not competitors:
        return "## Competitive Landscape\nCompetitor analysis has not completed yet."

    lines = ["## Competitive Landscape"]
    for competitor in competitors:
        name = _clean_report_text(competitor.get("name", "Unknown competitor"))
        description = _clean_report_text(
            competitor.get("description", "No description available.")
        )
        strength = _clean_report_text(
            competitor.get("strength", "No key strength available.")
        )
        lines.append(f"- **{name}** — {description}")
        lines.append(f"  - *Key strength:* {strength}")
    return "\n".join(lines)


def _clean_report_text(text: str) -> str:
    clean = re.sub(r"\s+", " ", str(text or "")).strip()
    clean = clean.strip("#*-` ")
    return clean or "Not available"


def _format_references(state: ResearchState) -> str:
    seen = set()
    refs = []
    
    for source in [state.get("documents", {}), state.get("curated_docs", {})]:
        for docs in source.values():
            if not isinstance(docs, list):
                continue
            for doc in docs:
                url = doc.get("url")
                if url and url not in seen:
                    seen.add(url)
                    title = doc.get("title", "Untitled")
                    refs.append(f"**{title}** — {url}")
                    
    lines = ["## References"]
    for i, ref in enumerate(refs[:10], 1):
        lines.append(f"{i}. {ref}")
        
    return "\n".join(lines)


async def editor_node(state: ResearchState) -> dict:
    company = state["company_name"]
    briefings = state.get("briefings", {})
    risk_assessment = _format_risk_assessment(state.get("risk_scores", {}))
    competitive_landscape = _format_competitive_landscape(
        state.get("competitors", [])
    )
    references = _format_references(state)
    print(f"Editor: compiling final report for {company}")

    company_section = briefings.get("company", "No company data available.")
    financial_section = briefings.get("financial", "No financial data available.")
    industry_section = briefings.get("industry", "No industry data available.")
    news_section = briefings.get("news", "No news data available.")

    report = f"""# {company} — Intelligence Report
*Generated by PrismIntel*

---

## Executive Summary

This report provides a comprehensive intelligence analysis of **{company}** covering company fundamentals, financial performance, industry positioning, and recent developments. Risk assessment and competitive landscape analysis are included to support strategic decision-making.

---

{company_section}

---

{financial_section}

---

{industry_section}

---

{news_section}

---

{risk_assessment}

---

{competitive_landscape}

---

{references}
"""
    print(f"Editor: report compiled ({len(report)} chars)")
    return {"final_report": report, "status": "complete"}


